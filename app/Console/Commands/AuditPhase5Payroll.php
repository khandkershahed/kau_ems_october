<?php
namespace App\Console\Commands;

use App\Models\EmployeeInfo;
use App\Models\SalaryGenerate;
use App\Services\SalaryBillCompositionService;
use App\Services\SalaryBillReconciliation;
use DomainException;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

/** Read-only reconciliation of all employee profiles against October/current period. */
final class AuditPhase5Payroll extends Command
{
    protected $signature='kau:audit-phase5-payroll {--year=2026} {--month=10}';
    protected $description='Read-only employee-wise calculation and posted bill/GPF/bank advice reconciliation';

    public function handle(): int
    {
        $year=(int)$this->option('year');$month=(int)$this->option('month');
        if ($year<2020||$year>2100||$month<1||$month>12) { $this->error('Invalid period.'); return self::FAILURE; }
        $prefix=storage_path('app/kau_phase5_'.sprintf('%04d_%02d',$year,$month));
        $out=fopen($prefix.'_employee_reconciliation.csv','w');
        $columns=['profile_id','user_id','employee_code','status','issue','pay_scale','grade','fixation_id','calculation_version_id',
            'regular_basic','regular_gross','regular_gpf','regular_deduction','regular_net','arrear_additions',
            'arrear_deductions','arrear_gpf','combined_net','bank_account_id','bank_last_four','bill_id',
            'source_hash','saved_bill_total','gpf_ledger_amount','supplementary_gpf_journal'];
        fputcsv($out,$columns);
        $counts=[];$totals=['regular_gross'=>0,'regular_deduction'=>0,'regular_net'=>0,'arrear_additions'=>0,
            'arrear_deductions'=>0,'arrear_gpf'=>0,'combined_net'=>0];
        EmployeeInfo::orderBy('id')->chunkById(50,function($profiles) use($year,$month,$out,$columns,&$counts,&$totals){
            foreach($profiles as $profile){
                $row=array_fill_keys($columns,null);
                $row['profile_id']=$profile->id;$row['user_id']=$profile->user_id;$row['employee_code']=$profile->employeeCode;
                $bills=SalaryGenerate::where('user_id',$profile->user_id)->where('monthId',$month)
                    ->where('salaryGenerationYear',$year)->get();
                try {
                    if($bills->count()>1) throw new DomainException('Duplicate saved salary bills.');
                    if($bills->count()===1){
                        $bill=$bills->first();$row['bill_id']=$bill->id;
                        $row['saved_bill_total']=$bill->salaryTotal;
                        $source=Schema::hasTable('salary_bill_source_links')?
                            DB::table('salary_bill_source_links')->where('salary_generate_id',$bill->id)->first():null;
                        if(!$source){$row['status']='HISTORICAL_BILL_NO_PHASE5_SOURCE';
                            $row['issue']='Existing bill was not generated by Phase 5; preserved unchanged.';
                            $row['combined_net']=$bill->salaryTotal;
                        }else{
                            $snap=json_decode($source->source_snapshot,true);
                            if(!is_array($snap)||$source->source_hash!==hash('sha256',json_encode(
                                array_diff_key($snap,['source_hash'=>null]),JSON_UNESCAPED_UNICODE|JSON_THROW_ON_ERROR))){
                                throw new DomainException('Frozen source hash mismatch.');
                            }
                            $verify=SalaryBillReconciliation::verify($bill,$bill->salaryAllowanceCalcObject??[],
                                $bill->salaryDeductionCalcObject??[]);
                            if($verify['issues']) throw new DomainException(implode('|',$verify['issues']));
                            if(abs((float)$source->net_payable-(float)$bill->salaryTotal)>0.009 ||
                                (string)$snap['bank_account_no']!==(string)$bill->bankAccountNo){
                                throw new DomainException('Frozen bank advice or Net Payable mismatch.');
                            }
                            $regularGpf=(float)$snap['regular']['gpf_deduction'];
                            $ledger=DB::table('general_provident_funds')->where('salary_generate_id',$bill->id)
                                ->where('type','monthly_deduction')->get();
                            if(($regularGpf>0 && $ledger->count()!==1) ||
                                ($regularGpf===0.0 && $ledger->isNotEmpty()) ||
                                ($ledger->count()===1 && abs((float)$ledger->first()->contributionAmount-$regularGpf)>0.009)) {
                                throw new DomainException('Regular GPF monthly ledger mismatch.');
                            }
                            $supp=DB::table('salary_bill_arrear_gpf_entries')->where('salary_generate_id',$bill->id)->sum('signed_amount');
                            if(abs((float)$supp-(float)$snap['arrear_gpf'])>0.009){
                                throw new DomainException('Supplementary GPF journal mismatch.');
                            }
                            $row['status']='POSTED_COMPONENT_MATCH';$row['source_hash']=$source->source_hash;
                            $row['gpf_ledger_amount']=$regularGpf;
                            $row['supplementary_gpf_journal']=$supp;
                            $this->fillAmounts($row,$snap);
                        }
                    }else{
                        $snap=app(SalaryBillCompositionService::class)->compose((int)$profile->user_id,$year,$month);
                        $row['status']='READY_DRAFT_NOT_POSTED';$row['source_hash']=$snap['source_hash'];
                        $this->fillAmounts($row,$snap);
                    }
                } catch(\Throwable $e){
                    $row['status']='BLOCKED';$row['issue']=$e->getMessage();
                }
                $counts[$row['status']]=($counts[$row['status']]??0)+1;
                if(in_array($row['status'],['READY_DRAFT_NOT_POSTED','POSTED_COMPONENT_MATCH'],true)){
                    foreach($totals as $k=>&$v)$v+=(float)($row[$k]??0);
                    unset($v);
                }
                fputcsv($out,array_map(fn($k)=>$row[$k],$columns));
            }
        });
        fclose($out);
        $controls=fopen($prefix.'_control_totals.csv','w');fputcsv($controls,['metric','amount_or_count']);
        foreach($counts as $status=>$count)fputcsv($controls,['count_'.$status,$count]);
        foreach($totals as $metric=>$value)fputcsv($controls,[$metric,round($value,2)]);
        fclose($controls);
        $this->line('READ-ONLY Phase 5 audit complete. No bills, GPF, arrears or bank records changed.');
        $this->line('Employee CSV: '.$prefix.'_employee_reconciliation.csv');
        $this->line('Control CSV: '.$prefix.'_control_totals.csv');
        $this->table(['status','profiles'],collect($counts)->map(fn($v,$k)=>[$k,$v])->values()->all());
        $this->warn('Not a payment authorization. HR approval and bank/GPF reconciliation are separate.');
        return self::SUCCESS;
    }

    private function fillAmounts(array &$r,array $s): void
    {
        $r['pay_scale']=$s['pay_scale'];$r['grade']=$s['grade'];$r['fixation_id']=$s['fixation_id'];
        $r['calculation_version_id']=$s['calculation_version_id'];
        $r['regular_basic']=$s['regular']['basic'];$r['regular_gross']=$s['regular']['total_allowance'];
        $r['regular_gpf']=$s['regular']['gpf_deduction'];
        $r['regular_deduction']=$s['regular']['total_deduction'];$r['regular_net']=$s['regular']['net_salary'];
        $r['arrear_additions']=$s['arrear_payable'];$r['arrear_deductions']=$s['arrear_deduction'];
        $r['arrear_gpf']=$s['arrear_gpf'];$r['combined_net']=$s['net_payable'];
        $r['bank_account_id']=$s['bank_account_id'];
        $r['bank_last_four']=substr((string)$s['bank_account_no'],-4);
    }
}
